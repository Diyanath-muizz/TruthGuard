"""
agents/critic_agent.py
──────────────────────
Adversarial Critic Agent for TruthGuard.
Rigorously stress-tests draft answers using deterministic verification rules
and skeptical inspection: detecting contradictions, staleness, unsupported claims,
citation errors, and authority hierarchy violations.
"""

from __future__ import annotations

import logging
import re
from typing import Any, Dict, List, Optional

from agents import (
    CriticFinding,
    CriticOutput,
    DocumentSource,
    WorkflowState,
)
from verification.authority_rules import AuthorityRules
from verification.citation_validator import CitationValidator
from verification.contradiction_detector import ContradictionDetector
from verification.staleness_checker import StalenessChecker

logger = logging.getLogger(__name__)


class CriticAgent:
    """
    Adversarial fact-checker that challenges the Synthesizer's output.
    Never relies solely on self-reported LLM confidence.
    """

    def __init__(self) -> None:
        self.contradiction_detector = ContradictionDetector()

    def run(self, state: WorkflowState, db_session=None) -> WorkflowState:
        synth_out = state.synthesizer_output
        retriever_out = state.retriever_output
        sources = retriever_out.sources if retriever_out else []

        log_prefix = f"[CriticAgent (Round {state.revision_count + 1})]"
        state.workflow_log.append(f"{log_prefix} Commencing adversarial audit of draft answer.")

        if not synth_out:
            state.critic_output = CriticOutput(
                passes_verification=False,
                overall_confidence="none",
                requires_revision=False,
                requires_human_escalation=True,
                verification_summary="No draft answer was generated by the Synthesizer.",
            )
            return state

        if not sources and not synth_out.factual_claims:
            state.critic_output = CriticOutput(
                passes_verification=True,
                overall_confidence="none",
                requires_revision=False,
                requires_human_escalation=False,
                verification_summary="Insufficient evidence: corpus contains no groundable sources for this query.",
            )
            return state

        draft_text = synth_out.draft_answer
        claims = synth_out.factual_claims
        citations = synth_out.supporting_citations

        contradictions: List[CriticFinding] = []
        staleness_warnings: List[CriticFinding] = []
        unsupported_claims: List[CriticFinding] = []
        citation_errors: List[CriticFinding] = []
        authority_issues: List[CriticFinding] = []
        revision_suggestions: List[str] = []

        # -------------------------------------------------------------
        # 1. Check for blended contradictory values in draft text
        # (e.g. "12 to 15 days", "10-15", "approximately 12 or 15")
        # Mask out ISO dates (YYYY-MM-DD) to prevent hyphens in dates being misidentified
        # -------------------------------------------------------------
        draft_sans_dates = re.sub(r"\b\d{4}-\d{2}-\d{2}\b", "", draft_text)
        blend_pattern = re.search(r"\b(\d{1,3})\s*(?:to|-|or)\s*(\d{1,3})\s*(?:days|weeks|months|hours|percent|%|\$)?\b", draft_sans_dates, re.IGNORECASE)
        if blend_pattern:
            num1, num2 = blend_pattern.group(1), blend_pattern.group(2)
            if num1 != num2:
                contradictions.append(
                    CriticFinding(
                        finding_type="contradiction",
                        description=f"Draft answer inappropriately blended contradictory numeric values ({num1} and {num2}) into a compromise range.",
                        affected_claims=[c.claim_id for c in claims],
                        severity="critical",
                        recommendation="Do not blend contradictory numbers. Disclose the discrepancy and establish precedence using explicit trust rules.",
                    )
                )
                revision_suggestions.append(f"Remove the compromise range '{blend_pattern.group(0)}'. State the conflicting sources distinctly.")

        # -------------------------------------------------------------
        # 2. Check for Unsupported Claims
        # -------------------------------------------------------------
        for claim in claims:
            if not claim.supporting_sources:
                unsupported_claims.append(
                    CriticFinding(
                        finding_type="unsupported_claim",
                        description=f"Claim '{claim.claim_text}' has no supporting source passages in retrieved evidence.",
                        affected_claims=[claim.claim_id],
                        severity="critical",
                        recommendation="Remove ungrounded assertions or mark as unconfirmed.",
                    )
                )
                revision_suggestions.append(f"Remove unsupported claim: '{claim.claim_text}'")

        # -------------------------------------------------------------
        # 3. Staleness & Expiration Auditing
        # -------------------------------------------------------------
        cited_doc_ids = {str(c.doc_id) for c in citations}
        for s in sources:
            st = StalenessChecker.check_staleness({
                "status": "superseded" if s.is_superseded else "active",
                "effective_date": s.effective_date,
            })
            if st.is_stale:
                is_cited = str(s.doc_id) in cited_doc_ids
                staleness_warnings.append(
                    CriticFinding(
                        finding_type="staleness",
                        description=f"Source {s.filename} is stale or superseded: {st.reason}",
                        affected_claims=[],
                        severity="critical" if is_cited else "warning",
                        recommendation="Ensure the draft does not rely on outdated or superseded provisions as active policy.",
                    )
                )

        # -------------------------------------------------------------
        # 4. Authority & Hierarchy Violations
        # -------------------------------------------------------------
        if synth_out.conflicting_evidence:
            highest_cited_level = max((c.authority_level for c in citations), default=1)
            for conf in synth_out.conflicting_evidence:
                if conf.severity == "confirmed":
                    src_a = next((s for s in sources if str(s.doc_id) == str(conf.doc_a_id)), None)
                    src_b = next((s for s in sources if str(s.doc_id) == str(conf.doc_b_id)), None)
                    if src_a and src_b:
                        # Only flag if both conflicting sources have authority >= highest cited level
                        if src_a.authority_level >= highest_cited_level and src_b.authority_level >= highest_cited_level:
                            if src_a.authority_level == src_b.authority_level:
                                authority_issues.append(
                                    CriticFinding(
                                        finding_type="authority_violation",
                                        description=f"Unresolved conflict between equal authority sources {src_a.filename} and {src_b.filename}.",
                                        severity="critical",
                                        recommendation="System cannot arbitrarily pick one; require human review or abstention.",
                                    )
                                )

        # -------------------------------------------------------------
        # 5. Citation Validation
        # -------------------------------------------------------------
        raw_chunks = [{"chunk_id": s.chunk_id, "doc_id": s.doc_id, "text": s.passage_text} for s in sources]
        cit_results = CitationValidator.validate_all(citations, raw_chunks)
        for cr in cit_results:
            if not cr.is_valid:
                citation_errors.append(
                    CriticFinding(
                        finding_type="citation_error",
                        description=f"Citation {cr.citation_id} failed verification: {'; '.join(cr.errors)}",
                        severity="critical",
                        recommendation="Remove or correct invalid citation pointer.",
                    )
                )

        # Aggregate findings
        all_findings = (
            contradictions
            + staleness_warnings
            + unsupported_claims
            + citation_errors
            + authority_issues
        )

        critical_count = sum(1 for f in all_findings if f.severity == "critical")
        warning_count = sum(1 for f in all_findings if f.severity == "warning")

        passes = (critical_count == 0)
        requires_revision = False
        requires_human_escalation = False

        if not passes:
            # Check if this can be fixed via revision or requires human escalation
            has_equal_conflict = any(f.finding_type == "authority_violation" for f in authority_issues)
            if has_equal_conflict:
                requires_human_escalation = True
                requires_revision = False
            elif state.revision_count < state.max_revisions:
                requires_revision = True
            else:
                requires_human_escalation = True

        # Build human-readable summary
        if passes and warning_count == 0:
            summary = "Draft answer passed all adversarial verification checks with high grounding."
            confidence = "high"
        elif passes and warning_count > 0:
            summary = f"Draft answer passed verification with {warning_count} non-critical warnings (e.g. outdated historical references)."
            confidence = "medium"
        else:
            summary = f"Verification failed with {critical_count} critical issues and {warning_count} warnings."
            confidence = "low" if not requires_human_escalation else "none"

        state.critic_output = CriticOutput(
            passes_verification=passes,
            overall_confidence=confidence,
            contradictions=contradictions,
            staleness_warnings=staleness_warnings,
            unsupported_claims=unsupported_claims,
            citation_errors=citation_errors,
            authority_issues=authority_issues,
            all_findings=all_findings,
            requires_revision=requires_revision,
            requires_human_escalation=requires_human_escalation,
            revision_suggestions=revision_suggestions,
            verification_summary=summary,
        )

        state.workflow_log.append(
            f"{log_prefix} Audit complete. Passes: {passes}. "
            f"Critical issues: {critical_count}, Warnings: {warning_count}. "
            f"Requires revision: {requires_revision}, Requires escalation: {requires_human_escalation}."
        )
        return state
